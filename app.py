        if not re.match(id_pattern, id_number):
            flash("身分證字號格式不正確喔～")
            return render_template("auth/register.html", form=request.form, questions=SECURITY_QUESTIONS)

        email_pattern = r"^[^@\s]+@[^@\s]+\.[^@\s]+$"
        if not re.match(email_pattern, email):
            flash("Email 格式看起來怪怪的，請再確認。")
            return render_template("auth/register.html", form=request.form, questions=SECURITY_QUESTIONS)

