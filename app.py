@app.route("/search_activities", methods=["POST"])
def search_activities():
    data = request.json

    keyword = data.get("keyword", "").lower()
    theater = data.get("theater", "")
    hall = data.get("hall", "")
    start_date = data.get("start_date", "")
    end_date = data.get("end_date", "")
    is_ishow = data.get("is_ishow", False)

    results = []

    for act in ACTIVITIES:  # 你原本的活動資料 LIST
        # 關鍵字
        if keyword and keyword not in act["title"].lower():
            continue

        # 影城
        if theater and theater not in act["tags"]:
            continue

        # 廳別
        if hall and hall not in act["tags"]:
            continue

        # 日期區間
        act_start, act_end = act["date"].split(" ~ ")
        if start_date and start_date > act_end:
            continue
        if end_date and end_date < act_start:
            continue

        # iShow 活動
        if is_ishow and "iShow" not in act["tags"]:
            continue

        results.append(act)

    return jsonify(results)


