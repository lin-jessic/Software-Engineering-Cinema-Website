@app.route("/booking/payment", methods=["GET", "POST"])
@login_required
def booking_payment():
    booking = session.get("booking")
    if not booking:
        return redirect(url_for("booking_select"))

    # 如果是從選位頁過來（GET 帶 seats）
    seats_param = request.args.get("seats")
    if seats_param:
        booking["seats"] = seats_param.split(",") if seats_param else []
        session["booking"] = booking

    # ===== 計算金額 =====
    # 票種小計
    adult = int(booking.get("adult", 0))
    student = int(booking.get("student", 0))
    ticket_total = adult * 300 + student * 260
    booking["ticket_total"] = ticket_total

    # 餐飲小計：用 booking["foods"]
    foods = booking.get("foods", {}) or {}
    food_total = 0
    for item in foods.values():
        try:
            qty = int(item.get("qty", 0))
            price = int(item.get("price", 0))
        except (TypeError, ValueError):
            continue
        food_total += qty * price

    booking["food_total"] = food_total

    # 總金額
    total = ticket_total + food_total
    booking["total_price"] = total
    session["booking"] = booking

    # 取得目前會員儲值卡餘額
    user_id = session["user"]["id"]
    user = database.get_user_by_id(user_id)

    if request.method == "POST":
        pay_method = request.form.get("payment_method", "credit")
        booking["payment_method"] = pay_method
        session["booking"] = booking

        if pay_method == "card" and user["balance"] < total:
            return render_template(
                "booking/payment.html",
                booking=booking,
                user=user,
                error="儲值卡餘額不足，請改用其他付款方式或先儲值。"
            )

        return redirect(url_for("booking_confirm"))

    # GET：顯示付款頁
    return render_template(
        "booking/payment.html",
        booking=booking,
        user=user
    )

@app.route("/booking/confirm", methods=["GET", "POST"])
@login_required
def booking_confirm():
    # 前幾頁存好的訂票資訊
    booking = session.get("booking")

    # 如果沒有任何訂票資料，就導回選擇場次
    if not booking:
        return redirect(url_for("booking_select"))

    # ============== GET：只是顯示確認畫面 ==============
    if request.method == "GET":
        # 把前面整理好的餐飲字串也放進 booking，給模板顯示
        foods = booking.get("foods", {}) or {}
        food_parts = []
        if isinstance(foods, dict):
            for name, item in foods.items():
                qty = int(item.get("qty", 0) or 0)
                size = item.get("size", "")
                if qty > 0:
                    food_parts.append(f"{name} ({size}) x{qty}")
        booking["food_detail"] = "，".join(food_parts) if food_parts else None

        return render_template("booking/confirm.html", booking=booking)

    # ============== POST：按下「確認送出訂票」 ==============
    # 🔸 先做「必填欄位檢查」，沒填完就退回前一頁 🔸

    # 1) 電影、影城、日期、時間
    required_basic = ["movie", "theater", "date", "time"]
    for field in required_basic:
        if not booking.get(field):
            flash("請完整選擇電影、影城與場次後，再送出訂票！")
            return redirect(url_for("booking_select"))

    # 2) 座位
    seats_list = booking.get("seats")
    if not seats_list:
        flash("請先選擇座位再送出訂票！")
        return redirect(url_for("booking_select"))   # 如果有獨立選座頁，可改成對應的 endpoint

    # 3) 票數（至少要有一張）
    adult = int(booking.get("adult", 0) or 0)
    student = int(booking.get("student", 0) or 0)
    ticket_count = adult + student
    if ticket_count <= 0:
        flash("請至少選擇一張票再送出訂票！")
        return redirect(url_for("booking_select"))

    # 4) 付款方式
    payment_method = booking.get("payment_method")
    if not payment_method:
        flash("請選擇付款方式再送出訂票！")
        # 付款頁的 endpoint 叫什麼就填什麼，若不同名稱記得改掉
        return redirect(url_for("booking_payment"))

    # ==================================================
    # 通過檢查後，才真正寫進資料庫
    # ==================================================

    user_id = session["user"]["id"]

    # 座位：list → 字串
    if isinstance(seats_list, list):
        seats_str = ",".join(seats_list)
    else:
        seats_str = str(seats_list or "")

    # 餐飲字串（跟 GET 那段邏輯一樣）
    foods = booking.get("foods", {}) or {}
    food_parts = []
    if isinstance(foods, dict):
        for name, item in foods.items():
            qty = int(item.get("qty", 0) or 0)
            size = item.get("size", "")
            if qty > 0:
                food_parts.append(f"{name} ({size}) x{qty}")
    food_detail = "，".join(food_parts)

    # 金額
    total_price = int(booking.get("total_price", 0) or 0)

    # 電影名稱
    movie_id = booking.get("movie")  # 通常是 "1"、"2"…
    movie_title = get_movie_title(movie_id)

    # 建立訂單
    order_id = database.create_order(
        user_id=user_id,
        movie_title=movie_title,
        theater=booking.get("theater", ""),
        date=booking.get("date", ""),
        time=booking.get("time", ""),
        ticket_count=ticket_count,
        adult_count=adult,
        student_count=student,
        seats=seats_str,
        food_detail=food_detail,
        payment_method=payment_method,
        total_price=total_price,
    )

    # ===== 儲值卡扣款：付款方式為「card」就扣款 =====
    if payment_method == "card":
        success = database.use_balance(user_id, total_price)

        if not success:
            # 💥 餘額不足 → 把剛剛那筆訂單刪掉，避免產生無效訂單
            database.delete_order(order_id)
            flash("儲值卡餘額不足，無法完成付款。")
            return redirect(url_for("booking_payment"))

    # 用完就把暫存的 booking 清掉
    session.pop("booking", None)

    # 導到訂單詳情頁
    return redirect(url_for("order_detail", order_id=order_id))
