        password2     = request.form.get("password_confirm", "")
        sec_question  = request.form.get("security_question", "")
        sec_answer    = request.form.get("security_answer", "").strip()
        agree         = request.form.get("agree")

        # --------- 基本必填檢查 ---------
        if not all([username, id_number, email, phone,
                    birthday, bank_account, password,
                    password2, sec_question, sec_answer]):
            flash("請確認填寫完所有欄位 (ﾉ◕ヮ◕)ﾉ*:･ﾟ✧")
            return render_template("auth/register.html", form=request.form, questions=SECURITY_QUESTIONS)

