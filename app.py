            sec_answer   = request.form.get("security_answer", "").strip()

            # --- 密碼欄位（可不填） ---
            current_pw = request.form.get("current_password", "")
            new_pw = request.form.get("new_password", "")
            new_pw2 = request.form.get("new_password_confirm", "")

            # 1) 先更新基本資料（含 security 題目答案）
