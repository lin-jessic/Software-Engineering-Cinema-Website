@app.route("/forgot", methods=["GET", "POST"])
def forgot():
    # 第一次進來：只顯示輸入 email
    if request.method == "GET":
        return render_template("auth/forgot.html", step="email")

    step = request.form.get("step")

    # STEP 1：輸入 email → 查到題目才進下一步
    if step == "email":
        email = request.form.get("email", "").strip()

        user = database.get_user_by_email(email)  # 你要有這個 function
        if not user:
            flash("查無此電子郵件", "error")
            return render_template("auth/forgot.html", step="email")

        if not user.get("security_question"):
            flash("此帳號尚未設定忘記密碼題目，請聯絡客服或重新註冊", "error")
            return render_template("auth/forgot.html", step="email")

        return render_template(
            "auth/forgot.html",
            step="question",
            email=email,
            security_question=user["security_question"]
        )

    # STEP 2：回答題目 + 設新密碼
    if step == "question":
        email = request.form.get("email", "").strip()
        security_answer = request.form.get("security_answer", "").strip()
        new_password = request.form.get("new_password", "")
        confirm_password = request.form.get("confirm_password", "")

        user = database.get_user_by_email(email)
        if not user:
            flash("查無此電子郵件", "error")
            return render_template("auth/forgot.html", step="email")

        # 重新帶回題目（避免你錯誤時題目又變 None）
        security_question = user.get("security_question") or ""

        if not security_question:
            flash("此帳號尚未設定忘記密碼題目", "error")
            return render_template("auth/forgot.html", step="email")

        if security_answer != (user.get("security_answer") or ""):
            flash("忘記密碼答案不正確", "error")
            return render_template(
                "auth/forgot.html",
                step="question",
                email=email,
                security_question=security_question
            )

        if new_password != confirm_password:
            flash("兩次密碼輸入不一致", "error")
            return render_template(
                "auth/forgot.html",
                step="question",
                email=email,
                security_question=security_question
            )

        database.update_password(email, new_password)  # 你要有這個 function
        return redirect(url_for("login", reset="success"))

    # 其他不明 step
    return render_template("auth/forgot.html", step="email")

